#!/usr/bin/env python3
"""Score evals/adversarial and evals/good. No language model.

Writes evals/results/verify-report.md. Exits 1 when fewer than 95% of
adversarial notes are refused, when more than 10% of good notes are refused,
or when a refused note does not fail the rule named in its header.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import knowledge_note  # noqa: E402
import verify_note  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ADVERSARIAL = ROOT / "evals" / "adversarial"
GOOD = ROOT / "evals" / "good"
REPORT = ROOT / "evals" / "results" / "verify-report.md"
_EXPECT = re.compile(r"expect:\s*(PASS|FAIL)(?:\s+(R\d{2}))?", re.IGNORECASE)
INTERCEPT_MIN = 0.95
FALSE_POSITIVE_MAX = 0.10


def expect_of(text: str) -> tuple[str, str | None]:
    match = _EXPECT.search(text)
    if not match:
        return ("", None)
    kind = match.group(1).upper()
    rule = match.group(2).upper() if match.group(2) else None
    return (kind, rule)


def samples(directory: Path) -> list[Path]:
    return sorted(path for path in directory.glob("*.md") if path.is_file())


def score(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    kind, rule = expect_of(text)
    fields = knowledge_note.parse_frontmatter(text) or {}
    relative = str(fields.get("transcript_path") or "")
    if not relative:
        found = re.search(r"transcript_path:\s*([^\s`]+)", text)
        relative = found.group(1).strip('"') if found else ""
    transcript = ROOT / relative if relative else path.with_suffix(".missing.txt")
    expected_lang = fields.get("expected_lang") or None
    if expected_lang is None:
        found_lang = re.search(r"expected_lang:\s*([A-Za-z-]+)", text)
        expected_lang = found_lang.group(1) if found_lang else None
    job_status = fields.get("job_status") or None
    result = verify_note.verify(
        transcript,
        text,
        expected_lang=expected_lang,
        job_status=job_status,
    )
    failed = [item["id"] for item in result["rules"] if not item["ok"]]
    return {
        "path": path.relative_to(ROOT).as_posix(),
        "expect": kind,
        "rule": rule,
        "allowed": result["allowed"],
        "failed": failed,
        "reasons": result["reasons"],
    }


def _pct(part: int, whole: int) -> str:
    if whole == 0:
        return "n/a"
    return f"{(100.0 * part / whole):.1f}%"


def render(adversarial: list[dict], good: list[dict]) -> str:
    refused_bad = sum(1 for row in adversarial if not row["allowed"])
    refused_good = sum(1 for row in good if not row["allowed"])
    missed = [
        row
        for row in adversarial
        if row["rule"] and row["rule"] not in row["failed"]
    ]
    intercept = refused_bad / len(adversarial) if adversarial else 0.0
    false_positive = refused_good / len(good) if good else 1.0
    ok = (
        len(adversarial) >= 30
        and len(good) >= 15
        and intercept >= INTERCEPT_MIN
        and false_positive <= FALSE_POSITIVE_MAX
        and not missed
    )
    lines = [
        "# Verify report",
        "",
        "Generated by `python3 scripts/verify_report.py`. Rules are deterministic. No language model is called.",
        "",
        f"Adversarial refused: {refused_bad} / {len(adversarial)} (intercept {_pct(refused_bad, len(adversarial))}). Minimum {INTERCEPT_MIN:.0%}.",
        f"Good refused: {refused_good} / {len(good)} (false positive {_pct(refused_good, len(good))}). Maximum {FALSE_POSITIVE_MAX:.0%}.",
        f"Expected rule missed: {len(missed)}.",
        f"Result: {'pass' if ok else 'fail'}.",
        "",
        "## Adversarial",
        "",
        "| file | expect | result | rules |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for row in adversarial:
        expect = row["expect"] + (f" {row['rule']}" if row["rule"] else "")
        result = "PASS" if row["allowed"] else "FAIL"
        rules = ", ".join(row["failed"]) or ""
        lines.append(f"| `{row['path']}` | {expect} | {result} | {rules} |")
    lines.extend(
        [
            "",
            "## Good",
            "",
            "| file | expect | result | rules |",
            "| :--- | :--- | :--- | :--- |",
        ]
    )
    for row in good:
        result = "PASS" if row["allowed"] else "FAIL"
        rules = ", ".join(row["failed"]) or ""
        lines.append(f"| `{row['path']}` | PASS | {result} | {rules} |")
    if missed:
        lines.extend(["", "## Missed expected rule", ""])
        for row in missed:
            lines.append(
                f"- `{row['path']}` expected {row['rule']} but failed {', '.join(row['failed']) or 'nothing'}"
            )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    adversarial = [score(path) for path in samples(ADVERSARIAL)]
    good = [score(path) for path in samples(GOOD)]
    text = render(adversarial, good)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(text, encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT).as_posix()}")
    refused_bad = sum(1 for row in adversarial if not row["allowed"])
    refused_good = sum(1 for row in good if not row["allowed"])
    missed = [row for row in adversarial if row["rule"] and row["rule"] not in row["failed"]]
    intercept = refused_bad / len(adversarial) if adversarial else 0.0
    false_positive = refused_good / len(good) if good else 1.0
    print(
        f"adversarial {len(adversarial)} intercept {intercept:.1%} "
        f"good {len(good)} false-positive {false_positive:.1%} missed {len(missed)}"
    )
    if len(adversarial) < 30 or len(good) < 15:
        print("corpus is smaller than 30 adversarial and 15 good", file=sys.stderr)
        return 1
    if intercept < INTERCEPT_MIN or false_positive > FALSE_POSITIVE_MAX or missed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
